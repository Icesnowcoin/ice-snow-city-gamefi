#!/usr/bin/env python3
"""Check prerequisites for Ice Snow City real-device performance collection.

This is a preflight only. It never reports FPS, frame time, memory, or a
passing device result. A real-device report must still be collected on the
listed device and validated by analyze_real_device_performance.py.

Examples:
  python3 scripts/check_real_device_prerequisites.py
  python3 scripts/check_real_device_prerequisites.py --allow-missing --json
"""

from __future__ import annotations

import argparse
import json
import platform
import shutil
import subprocess
from typing import Any


def run(command: list[str]) -> dict[str, Any]:
    try:
        result = subprocess.run(command, capture_output=True, text=True, timeout=8)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return {"available": False, "command": command, "error": str(exc)}
    return {
        "available": result.returncode == 0,
        "command": command,
        "returncode": result.returncode,
        "stdout": result.stdout.strip(),
        "stderr": result.stderr.strip(),
    }


def android_probe() -> dict[str, Any]:
    adb = shutil.which("adb")
    if not adb:
        return {"tool": "adb", "installed": False, "devices": [], "note": "adb is not installed"}
    result = run([adb, "devices", "-l"])
    devices = []
    for line in result.get("stdout", "").splitlines()[1:]:
        if line.strip() and not line.startswith("*"):
            fields = line.split()
            if len(fields) >= 2:
                devices.append({"serial": fields[0], "state": fields[1], "raw": line})
    return {"tool": "adb", "installed": True, "devices": devices, "probe": result}


def ios_probe() -> dict[str, Any]:
    xcrun = shutil.which("xcrun")
    if not xcrun:
        return {"tool": "xcrun", "installed": False, "devices": [], "note": "xcrun is not installed (requires macOS/Xcode)"}
    result = run([xcrun, "xctrace", "list", "devices"])
    lines = [line.strip() for line in result.get("stdout", "").splitlines() if line.strip()]
    devices = [line for line in lines if "Simulator" not in line and "Xcode" not in line]
    return {"tool": "xcrun", "installed": True, "devices": devices, "probe": result}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true", help="print machine-readable JSON")
    parser.add_argument("--allow-missing", action="store_true", help="return success for preparation on a machine without devices")
    args = parser.parse_args()

    report = {
        "status": "preflight-only",
        "validation": "pending",
        "platform": platform.platform(),
        "android": android_probe(),
        "ios": ios_probe(),
        "realDeviceEvidence": False,
        "message": "No performance or pass/fail evidence is generated by this preflight.",
    }
    has_android = any(item.get("state") == "device" for item in report["android"].get("devices", []))
    has_ios = bool(report["ios"].get("devices"))
    report["readyTargets"] = {"android": has_android, "ios": has_ios}
    report["nextStep"] = "Collect baseline and snow JSON on each target, then run analyze_real_device_performance.py."

    print(json.dumps(report, indent=2, ensure_ascii=False) if args.json else (
        f"preflight-only: Android={'ready' if has_android else 'missing'}, "
        f"iOS={'ready' if has_ios else 'missing'}; real-device validation remains pending."
    ))
    return 0 if args.allow_missing or has_android or has_ios else 2


if __name__ == "__main__":
    raise SystemExit(main())
